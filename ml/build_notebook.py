def code_cell(source: str) -> dict:
    return {
        "cell_type": "code",
        "execution_count": None,
        "metadata": {},
        "outputs": [],
        "source": source.strip().splitlines(keepends=True),
    }


def markdown_cell(source: str) -> dict:
    return {
        "cell_type": "markdown",
        "metadata": {},
        "source": source.strip().splitlines(keepends=True),
    }


def shared_sources_cell() -> dict:
    lines = ["# Generated from backend/. Do not edit here.", "SHARED_SOURCES = {"]
    for relative_path in SHARED_FILES:
        source = (BACKEND / relative_path).read_text(encoding="utf-8")
        lines.append(f"    {relative_path!r}: {source!r},")
    lines.append("}")
    return code_cell("\n".join(lines))


def main() -> None:
    cells = [
        markdown_cell(INTRO),
        shared_sources_cell(),
        markdown_cell("## 1. Setup"),
        code_cell(SETUP),
        markdown_cell("## 2. Download CirCor"),
        code_cell(DOWNLOAD),
        markdown_cell("## 3. Labels and patient-level split"),
        code_cell(LABELS),
        markdown_cell("## 4. Load the CardioPHON encoder"),
        code_cell(ENCODER),
        markdown_cell("## 5. Compute embeddings"),
        code_cell(EMBEDDINGS),
        markdown_cell("## 6. Train the classifier"),
        code_cell(TRAIN),
        markdown_cell("## 7. Choose the threshold and test"),
        code_cell(EVALUATE),
        markdown_cell("## 8. Export"),
        code_cell(EXPORT),
    ]
    notebook = {
        "cells": cells,
        "metadata": {
            "accelerator": "GPU",
            "colab": {"gpuType": "T4"},
            "kernelspec": {"display_name": "Python 3", "name": "python3"},
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(json.dumps(notebook, indent=1) + "\n", encoding="utf-8")
    print(f"Wrote {TARGET}")


if __name__ == "__main__":
    main()
